                'name' => 'US Dollar',
                'iso_code' => 'USD',
                'rate' => 1.0000
            ]
        );

        $eurCurrency = Currency::firstOrCreate(
            ['code' => 'EUR'],
            [
                'name' => 'Euro',
                'iso_code' => 'EUR',
                'rate' => 0.8500
            ]
