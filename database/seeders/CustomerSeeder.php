                    'notes' => $faker->optional()->sentence(),
                    'is_active' => true,
                ]);

                if ($faker->boolean(50)) {
                    CustomerOpeningBalance::create([
                        'customer_id' => $customer->id,
                        'currency_id' => $eurCurrency->id,
                        'opening_amount' => $faker->numberBetween(800, 8000),
                        'opening_date' => $faker->date(),
                        'notes' => $faker->optional()->sentence(),
                        'is_active' => true,
                    ]);
                }
            }
