                'title' => Arr::random(['Mr.', 'Mrs.', 'Ms.', 'Dr.', 'Prof.']),
                'name' => $faker->name(),
                'work_phone' => $faker->optional()->phoneNumber(),
                'mobile' => $faker->optional()->phoneNumber(),
                'position' => $faker->optional()->jobTitle(),
                'extension' => $faker->optional()->numerify('###'),
